import colorsys
import tkinter as tk

from blocks import ImmovableBlock, MovableBlock

# Colors
AIR_COLOR = "#ffffff"
AIR_OUTLINE = "#d9d9d9"
IMMOVABLE_COLOR = "#8c8c8c"
IMMOVABLE_OUTLINE = "#4d4d4d"
OBJECTIVE_COLOR = "#ffb3b3"     # Empty objective cell
OBJECTIVE_OUTLINE = "#e03030"   # Border of the objective cell, kept visible when a block covers it


class BoardPathViewer:
    """
    Window to browse the states of a solution path, one state at a time.

    layouts : list of board.board (2D lists of Blocks), one per state of the path, in order
    objective : list of [row, col], the cells of the objective

    Usage : BoardPathViewer(layouts, objective).show()
    """

    CELL_MAX = 60  # Max size (px) of a cell at the initial window size

    def __init__(self, layouts: list[list[list]], objective: list[list[int, int]]):
        if not layouts:
            raise ValueError("no state to display")

        self.layouts = layouts
        self.objective = {(row, col) for row, col in objective}
        self.total = len(layouts)
        self.index = 0

        self.colors = self.buildColors()

        # Window
        rows, cols = len(layouts[0]), len(layouts[0][0])
        self.root = tk.Tk()
        self.root.title("Chemin solution")

        self.canvas = tk.Canvas(self.root, width=cols * self.CELL_MAX, height=rows * self.CELL_MAX,
                                bg="white", highlightthickness=0)
        self.canvas.pack(fill="both", expand=True)

        bar = tk.Frame(self.root)
        bar.pack(fill="x", pady=6)
        bar.columnconfigure(1, weight=1)

        self.prevButton = tk.Button(bar, text="◀ Précédent état", command=self.previous)
        self.prevButton.grid(row=0, column=0, padx=8)
        self.counter = tk.Label(bar, font=("Segoe UI", 12, "bold"))
        self.counter.grid(row=0, column=1)
        self.nextButton = tk.Button(bar, text="Prochain état ▶", command=self.next)
        self.nextButton.grid(row=0, column=2, padx=8)

        self.canvas.bind("<Configure>", lambda event: self.draw())
        self.root.bind("<Left>", lambda event: self.previous())
        self.root.bind("<Right>", lambda event: self.next())

    # ========== #
    # Navigation #
    # ========== #
    def show(self):
        """
        Opens the window (blocks until it is closed)
        """
        self.draw()
        self.root.mainloop()

    def next(self):
        if self.index < self.total - 1:
            self.index += 1
            self.draw()

    def previous(self):
        if self.index > 0:
            self.index -= 1
            self.draw()

    # ======= #
    # Drawing #
    # ======= #
    def buildColors(self) -> dict[int, str]:
        """
        One distinct color per MovableBlock id (golden-ratio hue steps keep consecutive ids far apart)
        """
        ids = sorted({block.id for layout in self.layouts for row in layout for block in row
                      if isinstance(block, MovableBlock)})
        colors = {}
        for i, id in enumerate(ids):
            r, g, b = colorsys.hsv_to_rgb((i * 0.618034) % 1, 0.55, 0.95)
            colors[id] = "#{:02x}{:02x}{:02x}".format(int(r * 255), int(g * 255), int(b * 255))
        return colors

    def draw(self):
        layout = self.layouts[self.index]
        rows, cols = len(layout), len(layout[0])

        cell = min(self.canvas.winfo_width() / cols, self.canvas.winfo_height() / rows)
        x0 = (self.canvas.winfo_width() - cell * cols) / 2
        y0 = (self.canvas.winfo_height() - cell * rows) / 2
        font = ("Segoe UI", max(int(cell * 0.4), 6), "bold")

        self.canvas.delete("all")
        for row in range(rows):
            for col in range(cols):
                block = layout[row][col]
                x1, y1 = x0 + col * cell, y0 + row * cell
                x2, y2 = x1 + cell, y1 + cell
                isObjective = (row, col) in self.objective

                if isinstance(block, MovableBlock):
                    color = self.colors[block.id]
                    self.canvas.create_rectangle(x1, y1, x2, y2, fill=color, outline=color)
                    self.canvas.create_text((x1 + x2) / 2, (y1 + y2) / 2, text=str(block.id),
                                            font=font, fill="#202020")
                elif isinstance(block, ImmovableBlock):
                    self.canvas.create_rectangle(x1, y1, x2, y2, fill=IMMOVABLE_COLOR, outline=IMMOVABLE_OUTLINE)
                else:  # AirBlock
                    self.canvas.create_rectangle(x1, y1, x2, y2, fill=OBJECTIVE_COLOR if isObjective else AIR_COLOR,
                                                 outline=AIR_OUTLINE)

                # Second layer : objective border drawn above whatever is in the cell
                if isObjective:
                    self.canvas.create_rectangle(x1 + 1, y1 + 1, x2 - 1, y2 - 1, outline=OBJECTIVE_OUTLINE, width=2)

        self.counter.config(text=f"État {self.index + 1}/{self.total}")
        self.prevButton.config(state="normal" if self.index > 0 else "disabled")
        self.nextButton.config(state="normal" if self.index < self.total - 1 else "disabled")


def showSolutionPath(layouts: list[list[list]], objective: list[list[int, int]]):
    """
    Opens a window to browse the solution path.

    layouts : the board.board of each state of the path, in order
    objective : cells of the objective, e.g. [[7,6],[7,7],[8,6],[8,7]]
    """
    BoardPathViewer(layouts, objective).show()
