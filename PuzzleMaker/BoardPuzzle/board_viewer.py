import colorsys
import tkinter as tk

from board_elements import ImmovableBoardElement, MovableBoardElement
from board import Board

# Colors
EMPTY_COLOR = "#ffffff"
EMPTY_OUTLINE = "#d9d9d9"
IMMOVABLE_COLOR = "#8c8c8c"
IMMOVABLE_OUTLINE = "#4d4d4d"
OBJECTIVE_COLOR = "#ffb3b3"     # Empty objective cell
OBJECTIVE_OUTLINE = "#e03030"   # Border of the objective cell, kept visible when a block covers it


class BoardPathViewer:
    """
    Window to browse the states of a solution path, one state at a time.

    boards : list of Board, one per state of the path, in order
    objective_coords : set of (row, col), the cells of the objective

    Usage : BoardPathViewer(boards, objective_coords).show()
    """

    CELL_MAX = 60  # Max size (px) of a cell at the initial window size

    def __init__(self, grids: list[list[int]], objective_coords: set[tuple[int,int]]):
        if not grids:
            raise ValueError("no state to display")

        self.grids = grids

        self.objective_coords = objective_coords
        self.total = len(grids)
        self.index = 0

        self.colors = self.build_colors()

        # Window
        rows, cols = len(grids[0]), len(grids[0][0])
        self.root = tk.Tk()
        self.root.title("Chemin solution")

        self.canvas = tk.Canvas(self.root, width=cols * self.CELL_MAX, height=rows * self.CELL_MAX,
                                bg="white", highlightthickness=0)
        self.canvas.pack(fill="both", expand=True)

        bar = tk.Frame(self.root)
        bar.pack(fill="x", pady=6)
        bar.columnconfigure(1, weight=1)

        self.previous_button = tk.Button(bar, text="◀ Précédent état", command=self.previous)
        self.previous_button.grid(row=0, column=0, padx=8)
        self.counter = tk.Label(bar, font=("Segoe UI", 12, "bold"))
        self.counter.grid(row=0, column=1)
        self.next_button = tk.Button(bar, text="Prochain état ▶", command=self.next)
        self.next_button.grid(row=0, column=2, padx=8)

        self.canvas.bind("<Configure>", lambda event: self.draw())
        self.root.bind("<Left>", lambda event: self.previous())
        self.root.bind("<Right>", lambda event: self.next())

    # ========== #
    # Navigation #
    # ========== #
    def show(self):
        """
        Opens the window (blocks until it is closed)
        """
        self.draw()
        self.root.mainloop()

    def next(self):
        if self.index < self.total - 1:
            self.index += 1
            self.draw()

    def previous(self):
        if self.index > 0:
            self.index -= 1
            self.draw()

    # ======= #
    # Drawing #
    # ======= #
    def build_colors(self) -> dict[int, str]:
        """
        One distinct color per MovableBoardElement id (golden-ratio hue steps keep consecutive ids far apart)
        """
        block_ids = sorted({element.id for grid in self.grids for row in grid for element in row
                      if isinstance(element, MovableBoardElement)})
        colors = {}
        for i, block_id in enumerate(block_ids):
            r, g, b = colorsys.hsv_to_rgb((i * 0.618034) % 1, 0.55, 0.95)
            colors[block_id] = "#{:02x}{:02x}{:02x}".format(int(r * 255), int(g * 255), int(b * 255))
        return colors

    def draw(self):
        grid = self.grids[self.index]
        rows, cols = len(grid), len(grid[0])

        cell = min(self.canvas.winfo_width() / cols, self.canvas.winfo_height() / rows)
        x0 = (self.canvas.winfo_width() - cell * cols) / 2
        y0 = (self.canvas.winfo_height() - cell * rows) / 2
        font = ("Segoe UI", max(int(cell * 0.4), 6), "bold")

        self.canvas.delete("all")
        for row in range(rows):
            for col in range(cols):
                element = grid[row][col]
                x1, y1 = x0 + col * cell, y0 + row * cell
                x2, y2 = x1 + cell, y1 + cell
                is_objective_cell = (row, col) in self.objective_coords

                if isinstance(element, MovableBoardElement):
                    color = self.colors[element.id]
                    self.canvas.create_rectangle(x1, y1, x2, y2, fill=color, outline=color)
                    self.canvas.create_text((x1 + x2) / 2, (y1 + y2) / 2, text=str(element.id),
                                            font=font, fill="#202020")
                elif isinstance(element, ImmovableBoardElement):
                    self.canvas.create_rectangle(x1, y1, x2, y2, fill=IMMOVABLE_COLOR, outline=IMMOVABLE_OUTLINE)
                else:  # EmptyBoardElement
                    self.canvas.create_rectangle(x1, y1, x2, y2, fill=OBJECTIVE_COLOR if is_objective_cell else EMPTY_COLOR,
                                                 outline=EMPTY_OUTLINE)

                # Second layer : objective border drawn above whatever is in the cell
                if is_objective_cell:
                    self.canvas.create_rectangle(x1 + 1, y1 + 1, x2 - 1, y2 - 1, outline=OBJECTIVE_OUTLINE, width=2)

        self.counter.config(text=f"État {self.index + 1}/{self.total}")
        self.previous_button.config(state="normal" if self.index > 0 else "disabled")
        self.next_button.config(state="normal" if self.index < self.total - 1 else "disabled")


def show_solution_path(boards: list[list[list]], objective_coords: dict[int,list[list[int, int]]]):
    """
    Opens a window to browse the solution path.

    boards : the Board of each state of the path, in order
    objective_coords : cells of the objective, e.g. [[7,6],[7,7],[8,6],[8,7]]
    """
    BoardPathViewer(boards, objective_coords).show()
